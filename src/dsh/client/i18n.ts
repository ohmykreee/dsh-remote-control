/** Every shipped dictionary, keyed by locale code. */
export const DICTS: Record<LocaleCode, Record<string, string>> = { zh, en };

let localeService: LocaleService | null = null;
let preference: PluginLanguage = 'dsh';
const listeners = new Set<() => void>();

/** Remember the host locale service so the panel can follow its locale. */
export function configureLocale(service: LocaleService): void {
  localeService = service;
}

/** Active DSH locale id, or an empty string before the service is ready. */
export function dshLocaleId(): string {
  try {
    const snapshot = localeService?.getLocale?.() ?? localeService?.getSnapshot?.();
    return String(snapshot?.active || '');
  } catch {
    return '';
  }
}

/**
 * Resolve a preference plus the current DSH locale into a shipped language.
 * Following DSH requires an exact locale-id match; the fallback is English.
 */
export function resolveLocale(preferenceValue: PluginLanguage, dshLocale: string): LocaleCode {
  if (preferenceValue === 'zh' || preferenceValue === 'en') return preferenceValue;
  const requested = String(dshLocale || '').trim().toLowerCase();
  const exact = SUPPORTED_LOCALES.find((id) => id === requested);
  return exact ?? 'en';
}

/** Language currently used to render the panel. */
export function currentLocale(): LocaleCode {
  return resolveLocale(preference, dshLocaleId());
}

/** Remember the saved plugin language and repaint bound panels. */
export function setPluginLanguage(value: unknown): void {
  const next: PluginLanguage = value === 'zh' || value === 'en' ? value : 'dsh';
  if (next === preference) return;
  preference = next;
  notifyLanguage();
}

/** Current preference (not the resolved language). */
export function getPluginLanguage(): PluginLanguage {
  return preference;
}

/** Notify panels when the plugin language preference changes. */
export function subscribePluginLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

function notifyLanguage(): void {
  for (const listener of [...listeners]) {
    try {
      listener();
    } catch {
      /* one broken panel must not stop the others */
    }
  }
}

/** Bundled dictionary lookup through the active language, then English. */
export function fallbackTranslate(key: string): string {
  const dict = DICTS[currentLocale()];
  return dict[key] ?? en[key] ?? key;
}

/** Translate one key with the plugin language preference applied. */
export function translate(key: string): string {
  return fallbackTranslate(key);
}

/**
 * React hook that re-renders the panel when DSH changes locale or the saved
 * plugin language changes. The translator reads the current state on every
 * call, so only a version tick is needed here.
 */
export function useTranslator(): Translator {
  const [, setVersion] = useState(0);
  useEffect(() => {
    const bump = (): void => setVersion((value) => value + 1);
    const offLanguage = subscribePluginLanguage(bump);
    const offLocale = localeService?.subscribe?.(bump);
    return () => {
      offLanguage();
      try {
        offLocale?.();
      } catch {
        /* ignore a disposed locale service */
      }
    };
  }, []);
  return translate;
}
