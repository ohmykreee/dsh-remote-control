#!/usr/bin/env node
/**
 * Compile the TypeScript source under `src/dsh` into the plugin's native
 * runtime layout:
 *
 *   src/dsh/index.ts          -> <root>/index.js
 *   src/dsh/lib/**\/*.ts      -> <root>/lib/**\/*.js
 *   src/dsh/client/index.ts   -> <root>/client.js (all client modules bundled)
 *
 * The client half is split into ordinary TypeScript modules (types, i18n,
 * API/state helpers, primitives, sections, panel) and concatenated here into
 * one module table. `client.js` is wrapped in the DSH browser module-loading
 * contract: a classic script that registers a lazy factory with
 * `window.__ModuleLoader__`, whose `require` provides the shared `react` module.
 * The Host half is emitted as native ESM, matching `"type": "module"`.
 *
 * The emitted files are local build artifacts. They are gitignored and were
 * removed from git with `git rm`: run `pnpm build` (or `pnpm install`, whose
 * postinstall runs this script) before loading the plugin. Terser minifies the
 * Host ESM output and the client factory after compilation.
 */

import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { minify } from 'terser';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const buildDir = path.join(root, '.build');
const hostTsconfig = 'tsconfig.dsh.json';
const clientTsconfig = 'tsconfig.dsh-client.json';
const outputFiles = ['index.js', 'client.js'];
const outputDirs = ['lib'];
const CLIENT_ENTRY = 'client/index.js';

const GENERATED = '/** Generated by scripts/build-dsh.mjs from src/dsh — do not edit. */';

function formatDiagnostics(diagnostics) {
  return ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: (fileName) => fileName,
    getCurrentDirectory: () => root,
    getNewLine: () => '\n',
  });
}

function compile(configName) {
  const configPath = path.join(root, configName);
  if (!existsSync(configPath)) throw new Error(`missing TypeScript config: ${configName}`);
  const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
  if (configFile.error) {
    console.error(formatDiagnostics([configFile.error]));
    process.exit(1);
  }
  const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, root, undefined, configPath);
  if (parsed.errors.length > 0) {
    console.error(formatDiagnostics(parsed.errors));
    process.exit(1);
  }
  const program = ts.createProgram({ rootNames: parsed.fileNames, options: parsed.options });
  const emitted = program.emit();
  const diagnostics = ts.getPreEmitDiagnostics(program).concat(emitted.diagnostics);
  if (diagnostics.length > 0) {
    console.error(formatDiagnostics(diagnostics));
    process.exit(1);
  }
}

function clean() {
  rmSync(buildDir, { recursive: true, force: true });
  for (const file of outputFiles) rmSync(path.join(root, file), { force: true });
  for (const dir of outputDirs) rmSync(path.join(root, dir), { recursive: true, force: true });
}

function prependGenerated(file) {
  const body = readFileSync(file, 'utf8');
  writeFileSync(file, `${GENERATED}\n${body}`, 'utf8');
}

function prependBanner(file, banner) {
  const body = readFileSync(file, 'utf8');
  writeFileSync(file, `${banner}\n${body}`, 'utf8');
}

/** Recursively list JavaScript files as absolute paths. */
function listJavaScript(directory) {
  const files = [];
  for (const entry of readdirSync(directory)) {
    const absolute = path.join(directory, entry);
    if (statSync(absolute).isDirectory()) files.push(...listJavaScript(absolute));
    else if (entry.endsWith('.js')) files.push(absolute);
  }
  return files.sort();
}

/** Minify one generated file; host files are ESM, client.js is a classic script. */
async function minifyJavaScript(file, module) {
  const source = readFileSync(file, 'utf8');
  const result = await minify(source, {
    ecma: 2022,
    module,
    compress: { passes: 2 },
    mangle: true,
    format: { comments: false },
  });
  if (!result.code) throw new Error(`terser produced no output for ${file}`);
  writeFileSync(file, `${result.code}\n`, 'utf8');
}

/** Recursively list the compiled client modules, using `/`-separated ids. */
function listClientModules(directory, prefix = '') {
  const files = [];
  for (const entry of readdirSync(directory)) {
    const absolute = path.join(directory, entry);
    const id = prefix ? `${prefix}/${entry}` : entry;
    if (statSync(absolute).isDirectory()) files.push(...listClientModules(absolute, id));
    else if (entry.endsWith('.js')) files.push(id);
  }
  return files.sort();
}

/**
 * Wrap the CommonJS client modules in the DSH loader factory contract.
 *
 * The client half is split into ordinary TypeScript modules for maintenance,
 * but DSH still expects one classic script. A tiny module table (with relative
 * `require` resolution) lets tsc keep its normal per-file CommonJS output while
 * the shipped artifact stays a single `client.js`; `react` and other bare
 * specifiers still resolve through the loader's shared `require`.
 */
function writeClientBundle() {
  const clientRoot = path.join(buildDir, 'client');
  const entryPath = path.join(clientRoot, ...CLIENT_ENTRY.split('/'));
  if (!existsSync(entryPath)) throw new Error(`client compiler produced no entry: ${entryPath}`);
  const modules = listClientModules(clientRoot);
  if (!modules.includes(CLIENT_ENTRY)) {
    throw new Error(`client entry ${CLIENT_ENTRY} was not emitted (found: ${modules.join(', ')})`);
  }

  const factoryModules = modules.map((id) => {
    const body = readFileSync(path.join(clientRoot, ...id.split('/')), 'utf8');
    return `${JSON.stringify(id)}: function (module, exports, require) {\n${body}\n}`;
  });

  const wrapped = [
    "window.__ModuleLoader__.load({",
    "  id: 'dsh-remote-control',",
    '  factory(require) {',
    '    var __modules = {',
    factoryModules.join(',\n'),
    '    };',
    '    var __cache = Object.create(null);',
    '    function __normalize(from, request) {',
    "      var parts = from ? from.split('/') : [];",
    '      parts.pop();',
    "      for (var segment of request.split('/')) {",
    "        if (!segment || segment === '.') continue;",
    "        if (segment === '..') parts.pop();",
    '        else parts.push(segment);',
    '      }',
    "      return parts.join('/');",
    '    }',
    '    function __resolve(from, request) {',
    '      var target = __normalize(from, request);',
    '      if (__modules[target]) return target;',
    "      if (__modules[target + '.js']) return target + '.js';",
    "      if (__modules[target + '/index.js']) return target + '/index.js';",
    "      throw new Error('Cannot find module \"' + request + '\" from \"' + (from || '<entry>') + '\"');",
    '    }',
    '    function __require(from, request) {',
    "      if (request.charAt(0) !== '.') return require(request);",
    '      var id = __resolve(from, request);',
    '      var cached = __cache[id];',
    '      if (cached) return cached.exports;',
    '      var module = { exports: {} };',
    '      __cache[id] = module;',
    '      __modules[id](module, module.exports, function (next) { return __require(id, next); });',
    '      return module.exports;',
    '    }',
    `    return __require('', ${JSON.stringify(`./${CLIENT_ENTRY}`)});`,
    '  },',
    '});',
    '',
  ].join('\n');
  writeFileSync(path.join(root, 'client.js'), wrapped, 'utf8');
  return modules.length;
}

console.log('> compiling src/dsh (host, ESM)');
clean();
compile(hostTsconfig);
console.log('> compiling src/dsh/client/index.ts (browser, CommonJS modules)');
compile(clientTsconfig);

mkdirSync(path.join(root, 'lib'), { recursive: true });
cpSync(path.join(buildDir, 'host', 'index.js'), path.join(root, 'index.js'));
cpSync(path.join(buildDir, 'host', 'lib'), path.join(root, 'lib'), { recursive: true });
const clientModuleCount = writeClientBundle();

console.log('> minifying index.js, client.js, and lib/');
for (const file of [
  path.join(root, 'index.js'),
  path.join(root, 'client.js'),
  ...listJavaScript(path.join(root, 'lib')),
]) {
  await minifyJavaScript(file, file !== path.join(root, 'client.js'));
}
prependGenerated(path.join(root, 'index.js'));
prependBanner(
  path.join(root, 'client.js'),
  `${GENERATED}\n/* ${clientModuleCount} client modules bundled from src/dsh/client. */`,
);

console.log('> wrote index.js, client.js, lib/');
